// Build canonical full-rewrite inventory and 40-file batch lists (20 + 20 per batch).
// Priority partial wins first; giant paths last in their own tail batches.
// Usage: node scripts/fullRewriteInventory.mjs

import { readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = join(ROOT, 'scripts/full-rewrite');

const SKIP_DIR_NAMES = new Set(['node_modules', '__tests__']);
const GENERATED_SKIP = new Set([
  'src/for-both/setup-icons/onboardingIconRegistry.generated.js',
]);

const PRIORITY_FIRST = [
  'src/nutrition/food-search/searchFoods.js',
  'src/client-app/home/homeScreenPieces.jsx',
  'src/client-app/meals/LogTodaysMealsScreen.jsx',
  'src/client-app/workout-plans/MyWorkoutPlanScreen.jsx',
];

const GIANTS_LAST = [
  'src/ai-coach/conversation/CoachConversationScreen.jsx',
  'src/login-and-signup/LoginScreen.jsx',
  'src/login-and-signup/NewUserSetupScreen.jsx',
  'src/app-start/ClientAppStart.jsx',
  'src/trainer-app/home/TrainingHomeScreen.jsx',
  'src/trainer-app/home/homeLooks.js',
  'src/client-app/navigation/ClientMainScreen.jsx',
  'src/trainer-app/navigation/TrainerMainScreen.jsx',
  'src/nutrition/food-cards/FoodListScreen.jsx',
  'src/trainer-app/clients/ClientDetailScreen.jsx',
  'src/messaging/ChatScreen.jsx',
  'src/settings/SettingsScreen.jsx',
  'src/for-both/weekly-report/WeeklyReportScreen.jsx',
  'src/client-app/find-a-trainer/BrowseTrainersScreen.jsx',
];

function walkSourceFiles(directory, collected = []) {
  for (const name of readdirSync(directory)) {
    if (SKIP_DIR_NAMES.has(name)) continue;
    const absolutePath = join(directory, name);
    const stats = statSync(absolutePath);
    if (stats.isDirectory()) {
      walkSourceFiles(absolutePath, collected);
      continue;
    }
    if (!/\.(js|jsx)$/.test(name)) continue;
    const rel = absolutePath.slice(ROOT.length + 1);
    if (GENERATED_SKIP.has(rel)) continue;
    collected.push(rel);
  }
  return collected;
}

function chunk(array, size) {
  const chunks = [];
  for (let index = 0; index < array.length; index += size) {
    chunks.push(array.slice(index, index + size));
  }
  return chunks;
}

const allFiles = walkSourceFiles(join(ROOT, 'src')).sort();
const giantSet = new Set(GIANTS_LAST.filter((path) => allFiles.includes(path)));
const prioritySet = new Set(PRIORITY_FIRST.filter((path) => allFiles.includes(path)));

const middleFiles = allFiles.filter(
  (path) => !giantSet.has(path) && !prioritySet.has(path),
);

const ordered = [
  ...PRIORITY_FIRST.filter((path) => prioritySet.has(path)),
  ...middleFiles,
  ...GIANTS_LAST.filter((path) => giantSet.has(path)),
];

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(join(OUT_DIR, 'inventory-all.txt'), `${ordered.join('\n')}\n`, 'utf8');
writeFileSync(
  join(OUT_DIR, 'giants.txt'),
  `${[...giantSet].join('\n')}\n`,
  'utf8',
);
writeFileSync(
  join(OUT_DIR, 'priority-first.txt'),
  `${[...prioritySet].join('\n')}\n`,
  'utf8',
);

const batchesOf40 = chunk(ordered, 40);
for (let batchIndex = 0; batchIndex < batchesOf40.length; batchIndex += 1) {
  const batchNumber = batchIndex + 1;
  const forty = batchesOf40[batchIndex];
  const halfA = forty.slice(0, 20);
  const halfB = forty.slice(20, 40);
  writeFileSync(join(OUT_DIR, `batch${batchNumber}a.txt`), `${halfA.join('\n')}\n`, 'utf8');
  writeFileSync(join(OUT_DIR, `batch${batchNumber}b.txt`), `${halfB.join('\n')}\n`, 'utf8');
}

const readme = `# Full rewrite batch lists

Generated by \`node scripts/fullRewriteInventory.mjs\`. Re-run after editing priority/giant lists in that script.

- \`inventory-all.txt\` — ${ordered.length} files, priority → middle → giants
- \`batchNa.txt\` + \`batchNb.txt\` — 20 + 20 = 40 files per Metro gate
- \`giants.txt\` — giant paths (tail of inventory)

## Gate (after each batch rewrite)

1. \`node scripts/runBatchGate.mjs <N>\`
2. Full-file read per \`CODING_STYLE.md\`
3. \`npx expo export --platform ios --output-dir /tmp/cc-metro-batch\`
4. Metro fail → \`git restore --\` paths from batchNa + batchNb lists

## Parallel rewrite

Agent A: \`batchNa.txt\`. Agent B: \`batchNb.txt\`. Full Variation 3 — every line of syntax; freeze list unchanged.
`;

writeFileSync(join(OUT_DIR, 'README.md'), readme, 'utf8');

console.log(`inventory ${ordered.length} files`);
console.log(`batches ${batchesOf40.length} (40 files each, last may be shorter)`);
console.log(`wrote ${OUT_DIR}`);
